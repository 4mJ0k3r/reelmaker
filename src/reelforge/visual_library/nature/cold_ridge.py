def cold_pine(variant):
    """Static snow-loaded silhouettes, origin at the trunk foot."""
    narrow = variant == "pinnacle"
    leader = (3, -126) if narrow else (20, -84)
    bark = ((-7, 0), (-4, -40), leader, (leader[0] + 4, leader[1] + 3), (4, -40), (5, -9), (8, 0))
    silhouette = PINNACLE if narrow else WINDSHEAR
    commands = [
        DrawPath(
            ellipse(5, 1, 22, 4.5), gradient(color("273c52", 0.44), color("273c52", 0), -3, 6)
        ),
        polygon(bark, gradient(color("546473"), color("302e31"), -70, 0)),
        polygon(((-6, -1), (-3, -33), (0, -41), (-1, -12), (-3, 0)), color("8b8581", 0.53)),
        polygon(silhouette, gradient(color("345361"), color("203447"), -110, -20)),
        polygon(
            ((1, -72), (12, -68), (25, -53), (15, -54), (30, -37), (13, -41), (5, -31), (-4, -35)),
            color("152d3e", 0.52),
        ),
    ]
    for cap in SNOW_CAPS[variant]:
        top = min(p[1] for p in cap)
        commands.append(polygon(cap, gradient(color("d0dde4"), color("718da4"), top, top + 23)))
    commands.extend(
        (
            line(((-2, -32), (-12, -30), (-19, -26)), color("6b8799", 0.65), 0.8),
            line(((1, -28), (10, -28), (17, -25)), color("101f2e", 0.52), 1.1),
            polygon(((-12, 2), (-7, -3), (-3, 0), (6, -2), (13, 3)), color("a9c0cf", 0.79)),
        )
    )
    return tuple(commands)


