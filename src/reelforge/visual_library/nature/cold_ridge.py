def ridge_wind(breeze, seconds):
    """Short low-contrast streaks above and below the protected action band."""
    commands = []
    for i in range(24):
        x = (variation(411, i) * 600 + seconds * (25 + breeze * 28)) % 600 - 115
        y = (82 + variation(412, i) * 266) if i < 16 else (553 + variation(412, i) * 78)
        length = 7 + variation(413, i) * 19
        commands.append(
            line(
                ((x, y), (x + length, y + length * 0.16)),
                color("dde9f3", (0.07 + variation(414, i) * 0.11) * breeze),
                0.72,
            )
        )
    return tuple(commands)
